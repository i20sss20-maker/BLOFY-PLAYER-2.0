const TRACKS_BY_ID = new Map(ANIS_AUDIO_TRACKS.map(item => [item.id,item]));
const UPSTREAM_ORIGIN = 'http://radio.anisfm.vip';

/** Clients see only first-party, code-protected proxy URLs. */
export function anisAudioPublicCatalog(base = 'https://blofyplayer.com') {
  return ANIS_AUDIO_TRACKS.map(({id,label,group}) => ({
    id,label,group,format:'progressive',delaySeconds:0,
    playbackUrl: base + '/api/v1/stream/media/audio/' + id
  }));
}
export function anisAudioSourceFor(id, token) {
  const track = TRACKS_BY_ID.get(String(id||''));
  const privateToken=String(token||'').trim();
  if(!track || !/^[A-Za-z0-9_-]{8,128}$/.test(privateToken))return null;
  // Both host and path are fixed, not influenced by client parameters.
  // The source uses raw HTTP; ONLY this exact supplied origin is allowed.
  return UPSTREAM_ORIGIN + track.sourcePath + '?token=' +
    encodeURIComponent(privateToken);
}
export function anisAudioEnabled(env = process.env) {
  return env.BLOFY_STREAM_ANIS_AUDIO_ENABLED === '1' &&
    /^[A-Za-z0-9_-]{8,128}$/.test(String(env.BLOFY_STREAM_ANIS_TOKEN||'').trim());
}

/**
 * MIME validation for a real radio source. Some authorized radio servers
 * send generic octet-stream instead of audio/mpeg; sniff only a fixed small
 * prefix, never trust a filename or proxy HTML/video as soundtrack audio.
 */
export function classifyAnisAudioMime(contentType,firstChunk) {
  const type=String(contentType||'').split(';',1)[0].trim().toLowerCase();
  const accepted=new Set([
    'audio/mpeg','audio/mp3','audio/aac','audio/aacp','audio/x-aac',
    'audio/mp4','audio/ogg','audio/wav','audio/x-wav',
    'audio/flac','audio/x-flac','audio/opus'
  ]);
  if(accepted.has(type))return type==='audio/mp3'?'audio/mpeg':type;
  if(!['application/octet-stream','binary/octet-stream',''].includes(type))
    return null;
  const bytes=Buffer.isBuffer(firstChunk)?firstChunk:Buffer.from(firstChunk||[]);
  if(bytes.length>=3&&bytes.toString('ascii',0,3)==='ID3')return 'audio/mpeg';
  if(bytes.length>=2&&bytes[0]===0xff&&(bytes[1]&0xf6)===0xf0)return 'audio/aac';
  if(bytes.length>=2&&bytes[0]===0xff&&(bytes[1]&0xe0)===0xe0)return 'audio/mpeg';
  if(bytes.length>=4&&bytes.toString('ascii',0,4)==='OggS')return 'audio/ogg';
  if(bytes.length>=4&&bytes.toString('ascii',0,4)==='fLaC')return 'audio/flac';
  if(bytes.length>=12&&bytes.toString('ascii',0,4)==='RIFF'&&
      bytes.toString('ascii',8,12)==='WAVE')return 'audio/wav';
  return null;
}

/**
 * Operator-only preflight for ONE permitted source at a time. It never
 * requests arbitrary URLs and never serializes token-bearing URLs to results.
 * Preview reads just the first chunk and cancels to avoid forwarding radio
 * broadcasts, hanging connections or opening many upstream streams.
 */
export async function probeAnisAudioTrack(id,{
  env=process.env,fetchImpl=globalThis.fetch,timeoutMs=6000
}={}){
  if(!anisAudioEnabled(env))return {id,ok:false,reason:'not_configured'};
  const source=anisAudioSourceFor(id,env.BLOFY_STREAM_ANIS_TOKEN);
  if(!source)return {id,ok:false,reason:'unknown_audio_id'};
  const abort=new AbortController();
  const timer=setTimeout(()=>abort.abort(),Math.min(Math.max(timeoutMs,1000),8000));
  let response,reader;
  try{
    response=await fetchImpl(source,{
      method:'GET',redirect:'manual',signal:abort.signal,
      headers:{accept:'audio/*', 'user-agent':'BLOFY-STREAM-Owner-Audio-Preflight/1.0'}
    });
    const httpStatus=response.status;
    if(httpStatus!==200&&httpStatus!==206)
      return {id,ok:false,reason:'upstream_http',httpStatus};
    const headerType=response.headers.get('content-type');
    if(!response.body)return {id,ok:false,reason:'empty_body'};
    reader=response.body.getReader();
    const first=await reader.read();
    if(first.done||!first.value?.length)
      return {id,ok:false,reason:'no_audio_bytes'};
    const contentType=classifyAnisAudioMime(headerType,first.value);
    if(!contentType)return {id,ok:false,reason:'unsupported_audio_format'};
    return {id,ok:true,contentType};
  }catch{
    return {id,ok:false,reason:abort.signal.aborted?'timeout':'network_unreachable'};
  }finally{
    clearTimeout(timer);
    abort.abort();
    if(reader){
      try{await reader.cancel()}catch{}
      try{reader.releaseLock()}catch{}
    }else if(response?.body&&!response.body.locked){
      try{await response.body.cancel()}catch{}
    }
  }
}
